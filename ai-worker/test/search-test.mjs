// Tavily araması ve soru seçimi testi: node test/search-test.mjs (internete bağlanmaz, Tavily ve Workers AI taklit edilir).
import { _askFree, _searchQuery } from "../src/index.js";
let fail = 0;
const ok = (c, m) => { console.log((c ? "PASS " : "FAIL ") + m); if (!c) fail++; };
const msg = (t) => [{ role: "user", content: t }];
ok(_searchQuery({ search: "nazi almanya hangi sene kaybetti" }, []) === "nazi almanya hangi sene kaybetti", "genel soru aranır");
ok(_searchQuery({ search: "Kadraj'da hikâye nasıl paylaşılır?" }, []) === "", "uygulama sorusu aranmaz");
ok(_searchQuery({ search: "selam" }, []) === "", "selam aranmaz");
ok(_searchQuery({ search: "bugün istanbulda hava durumu" }, []) !== "", "güncel soru aranır");
ok(_searchQuery({ search: true }, msg("ne var ne yok")) === "ne var ne yok", "search:true son mesajı arar");
ok(_searchQuery({}, msg("kim kazandı?")) === "", "search yoksa aranmaz");
let sent = null, sys = "";
const env = { TAVILY_API_KEY: " tvly-test ", AI: { run: async (m, o) => { sys = o.messages[0].content; return { response: "1945'te yenildi.\nKaynak: wikipedia.org" }; } } };
const fake = async (url, init) => { sent = { url, init }; return { ok: true, json: async () => ({ results: [{ title: "İkinci Dünya Savaşı", url: "https://tr.wikipedia.org/wiki/II", content: "Almanya 8 Mayıs 1945'te teslim oldu." }, { title: "kötü", url: "javascript:alert(1)", content: "x" }] }) }; };
let r = await _askFree(env, { system: "Sen Rota'sın.", messages: msg("uzun prompt"), search: "nazi almanya hangi sene kaybetti" }, "u1", fake);
ok(sent && sent.url === "https://api.tavily.com/search" && sent.init.headers.Authorization === "Bearer tvly-test", "Tavily'ye doğru istek");
ok(JSON.parse(sent.init.body).query === "nazi almanya hangi sene kaybetti", "sorgu kişinin sorusu");
ok(sys.includes("8 Mayıs 1945") && sys.includes("tr.wikipedia.org") && sys.startsWith("Sen Rota'sın."), "sonuçlar sisteme eklendi");
ok(r.data.searched === true && r.data.sources.length === 1 && r.data.sources[0].url.startsWith("https://"), "kaynaklar döndü, javascript: atıldı");
sent = null;
r = await _askFree(env, { messages: msg("selam"), search: "selam" }, "u1", fake);
ok(sent === null && r.data.searched === false, "selamda arama yok");
sent = null;
r = await _askFree({ AI: env.AI }, { messages: msg("x"), search: "nazi almanya hangi sene kaybetti" }, "u1", fake);
ok(sent === null && r.status === 200, "anahtar yoksa aramadan çalışır");
const bad = async () => ({ ok: false, json: async () => ({}) });
r = await _askFree(env, { messages: msg("x"), search: "dünya kupasını kim kazandı" }, "u2", bad);
ok(r.status === 200 && r.data.searched === false, "Tavily hata verirse yine yanıt verir");
const lim = { ...env, SEARCH_DAILY_LIMIT: "2" };
let n = 0; const cnt = async (...a) => { n++; return fake(...a); };
for (let i = 0; i < 4; i++) await _askFree(lim, { messages: msg("x"), search: "dünya kupasını kim kazandı" }, "u3", cnt);
ok(n === 2, "günlük arama sınırı (2) çalışır");
console.log(fail ? fail + " hata" : "hepsi geçti");
process.exit(fail ? 1 : 0);
